function redLines(text: string): string[] {
  const stack: boolean[] = []; const lines: string[] = []
  for (const line of text.split('\n')) {
    if (/^IF DEF\(_RED\)/.test(line)) stack.push(true)
    else if (/^IF DEF\(_BLUE\)/.test(line)) stack.push(false)
    else if (/^ELSE/.test(line) && stack.length) stack[stack.length - 1] = !stack.at(-1)
    else if (/^ENDC/.test(line)) stack.pop()
    else if (stack.every(Boolean)) lines.push(line)
  }
  return lines
}
