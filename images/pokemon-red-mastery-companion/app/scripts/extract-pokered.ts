const objectToFlag: Record<string, string> = {}
for (const [ordinal, state] of toggleStates.entries()) {
  const key = `${state.map}:${state.object}`
  if (objectToFlag[key]) throw new Error(`Duplicate toggle map/object tuple: ${key}`)
  const flag = toggleNames[ordinal]!
  if (objectFlags[flag] !== ordinal) throw new Error(`Nonordinal toggle constant: ${flag}`)
  objectToFlag[key] = flag
}
const pickups: { area: string; x: number; y: number; rawItemId: number; kind: string; objectFlag?: string; hiddenFlagIndex?: number; inaccessible: boolean; sourceUrl: string }[] = []
