  const path = `data/maps/objects/${file}`; const content = read(path)
  const area = content.match(/def_warps_to (\w+)/)?.[1]
  if (!area) continue
  for (const m of content.matchAll(/^\s*object_event\s+(\d+),\s*(\d+),\s*SPRITE_POKE_BALL,[^\n]+/gm)) {
    const fields = m[0].trim().split(/,\s*/); const item = fields.at(-1)!.split(';')[0]!.trim()
    if (itemIds[item] === undefined) continue
    const objectName = fields[5]!.replace(/^TEXT_/, '')
    if (!objectToFlag[`${area}:${objectName}`]) throw new Error(`Visible pickup has no toggle: ${area}:${objectName}`)
    pickups.push({ area, x: +m[1]!, y: +m[2]!, rawItemId: itemIds[item]!, kind: 'visible', objectFlag: objectToFlag[`${area}:${objectName}`], inaccessible: false, sourceUrl: url(path) })
  }
